// Pixi's head alone (the logo's wordmark is not on its pixel grid and smears when scaled): 50 x 44 cells at 8 px.
{
  const w = HEAD_ROWS[0].length, h = HEAD_ROWS.length
  const cv = new Canvas(w, h)
  HEAD_ROWS.forEach((row, y) => {
    for (let x = 0; x < w; x++) if (row[x] !== '.') cv.set(x, y, parseInt(HEAD_PALETTE[row[x]].slice(1), 16))
  })
  writeFileSync(join(MEDIA, 'pixi-head.png'), encodePNG(upscale(cv.rgba, w, h, 8), w * 8, h * 8))
  console.log(`pixi-head: ${w * 8}x${h * 8}`)
}

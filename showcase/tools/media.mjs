// Builds the showcase's media: every clip's frames at 512 px (crisp, a quarter
// of the mod's 1024 px, plenty for a 1080p video) as media/<clip>-f<n>.png, the
// title slabs in the mod's own arcade lettering as media/title-<name>.png, and
// the logo. fframes embeds only the top level of media/, keyed by file name,
// hence the flat layout and the unique names. Run from the repo:
// node showcase/tools/media.mjs
import { writeFileSync, readdirSync, unlinkSync, copyFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { encodePNG, upscale } from '../../tools/png.mjs'
import { CLIPS, SIZE, Canvas, renderFrame, drawTitle } from '../../hooks/pixi.js'
import { HEAD_ROWS, HEAD_PALETTE } from '../../hooks/head.js'
import { drawStoryLayers, STORY_FRAMES, W as STORY_W, H as STORY_H } from './story.mjs'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url))) // showcase/
const REPO = dirname(ROOT)
const SCALE = 4

const MEDIA = join(ROOT, 'media')
// start clean: everything generated is a PNG; the fonts stay
for (const f of readdirSync(MEDIA)) if (f.endsWith('.png')) unlinkSync(join(MEDIA, f))
for (const clip of CLIPS) {
  for (let i = 0; i < clip.frames; i++) {
    const { canvas } = renderFrame(clip, i)
    writeFileSync(join(MEDIA, `${clip.id}-f${i}.png`), encodePNG(upscale(canvas.rgba, SIZE, SIZE, SCALE), SIZE * SCALE, SIZE * SCALE))
  }
  console.log(`${clip.id}: ${clip.frames} frames`)
}

// The story, at its own 240 x 135 (the video scales it by exactly 8), as two
// layers a frame: the room (bg) and the furniture with Pixi (fg), for parallax.
const phone = []
for (let i = 0; i < STORY_FRAMES; i++) {
  const { bg, fg, joints } = drawStoryLayers(i)
  if (!joints.reached) console.log(`story f${i}: an IK target is out of reach`)
  if (joints.phone) phone.push(`    (${i}, ${joints.phone[0].toFixed(1)}, ${joints.phone[1].toFixed(1)}),`)
  writeFileSync(join(MEDIA, `bg-f${i}.png`), encodePNG(bg.rgba, STORY_W, STORY_H))
  writeFileSync(join(MEDIA, `fg-f${i}.png`), encodePNG(fg.rgba, STORY_W, STORY_H))
}
writeFileSync(join(ROOT, 'src', 'phone.rs'), `//! Generated by tools/media.mjs: the centre of the phone's screen (story frame, x, y in the room's 240 x 135 px) while Pixi holds it.\npub const PHONE: &[(usize, f32, f32)] = &[\n${phone.join('\n')}\n];\n`)
console.log(`story: ${STORY_FRAMES} frames`)

// Title slabs on a transparent canvas, sized to the text, at 2x in the font then 4x in pixels.
// the slab palettes: face, lit band, extruded side
const PALETTES = {
  gold: {},
  cream: { face: 0xf1e9ff, lit: 0xffffff, side: 0x9c90c4 },
  blue: { face: 0x69a8bd, lit: 0xa9dcf5, side: 0x2f5f74 },
  pink: { face: 0xe86a8a, lit: 0xffb0c4, side: 0x8c2f4c },
  cyan: { face: 0x48c1c5, lit: 0xb5f4f6, side: 0x1f6f78 }, // Pixi's hair: the keyword colour
}
function slab(name, lines, s = 2) {
  const w = Math.max(...lines.map((l) => l.length)) * 6 * s + 16, h = lines.length * 9 * s + 16
  for (const [pal, opts] of Object.entries(PALETTES)) {
    const cv = new Canvas(w, h)
    drawTitle(cv, lines, w / 2, h / 2, s, opts)
    writeFileSync(join(MEDIA, `title-${name}-${pal}.png`), encodePNG(upscale(cv.rgba, w, h, SCALE), w * SCALE, h * SCALE))
  }
  console.log(`title ${name}: ${w}x${h}`)
}
